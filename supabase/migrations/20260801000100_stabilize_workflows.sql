revoke update on public.organizations, public.document_counters, public.profiles from authenticated;
revoke insert, update on public.loans from authenticated;
revoke insert on public.transactions, public.schedule_versions, public.installments,
  public.capital_payment_details, public.payment_adjustment_details, public.documents,
  public.audit_events from authenticated;
