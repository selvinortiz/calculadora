create or replace function public.server_edit_transaction(actor_id uuid, command jsonb)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare target public.transactions%rowtype;
begin
  perform private.assume_server_actor(actor_id);
  select * into target from public.transactions where id = (command->>'transactionId')::uuid;
  if not found then raise exception using errcode = 'P0001', message = 'transaction_not_found'; end if;
  if exists (
    select 1 from public.transactions later
    where later.loan_id = target.loan_id
      and later.status = 'posted'
      and later.ledger_sequence > target.ledger_sequence
  ) then
    raise exception using errcode = 'P0001', message = 'dependent_transactions_must_be_voided_first';
  end if;
  return public.edit_transaction(command);
end;
$$;

