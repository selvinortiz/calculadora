-- Keep financial and audit writes behind the application server while retaining
-- the authenticated user's identity for ownership checks and audit records.

alter table public.transactions
  add column ledger_sequence bigint generated by default as identity;
create unique index transactions_ledger_sequence_key
  on public.transactions (ledger_sequence);

create or replace function private.assume_server_actor(actor_id uuid)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if actor_id is null or not exists (select 1 from public.profiles where id = actor_id) then
    raise exception using errcode = '42501', message = 'valid_actor_required';
  end if;
  perform pg_catalog.set_config('request.jwt.claim.sub', actor_id::text, true);
  perform pg_catalog.set_config('request.jwt.claim.role', 'authenticated', true);
end;
$$;

create or replace function public.server_post_loan(actor_id uuid, command jsonb)
returns jsonb language plpgsql security definer set search_path = '' as $$
begin
  perform private.assume_server_actor(actor_id);
  return public.post_loan(command);
end;
$$;

